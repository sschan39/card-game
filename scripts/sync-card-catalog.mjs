import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const library = fileURLToPath(new URL('../packages/engine/src/library/', import.meta.url));

async function definitions(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return definitions(path);
    return entry.isFile() && entry.name.endsWith('.json') ? [path] : [];
  }));
  return files.flat().sort();
}

const seen = new Map();
const manifests = [];
for (const kind of ['cards', 'tokens']) {
  const directory = join(library, kind);
  const output = join(directory, 'manifest.generated.ts');
  const imports = [];
  const entries = [];
  for (const path of await definitions(directory)) {
    const source = relative(library, path).split(sep).join('/');
    let definition;
    try {
      definition = JSON.parse(await readFile(path, 'utf8'));
    } catch (error) {
      throw new Error(`${source}: ${error.message}`);
    }
    const id = definition?.id;
    if (typeof id !== 'string' || !/^[a-z0-9][a-z0-9_-]{0,127}$/.test(id)) {
      throw new Error(`${source}: invalid or missing definition ID.`);
    }
    if (seen.has(id)) throw new Error(`Duplicate definition ${id}: ${seen.get(id)} and ${source}`);
    seen.set(id, source);
    const binding = 'definition' + imports.length;
    const specifier = './' + relative(dirname(output), path).split(sep).join('/');
    imports.push(`import ${binding} from ${JSON.stringify(specifier)};`);
    entries.push(`  [${JSON.stringify(id)}]: ${binding},`);
  }
  const content = [
    '// Generated by npm run cards:sync. Edit the JSON definition files instead.',
    ...imports, '', 'const definitions: Record<string, unknown> = {', ...entries,
    '};', 'export default definitions;', '',
  ].join('\n');
  manifests.push({ output, content });
}

for (const { output, content } of manifests) {
  const previous = await readFile(output, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return '';
  });
  if (previous.replaceAll('\r\n', '\n') === content) continue;
  if (process.argv.includes('--check')) throw new Error('Card manifests are stale. Run npm run cards:sync.');
  await writeFile(output, content);
}
